const assert=require('node:assert/strict');
const fs=require('node:fs');
const core=require('../assets/investor-core.js');
const {validate,identityMatch}=require('./investor-schema.cjs');
const {csv}=require('./import-investors.cjs');
const data=require('../content/investors/profiles.json');
for(const p of data)assert.deepEqual(validate(p),[],p.id);
const source=data.find(p=>p.id==='2048-ventures'),p=structuredClone(source);
assert.equal(core.match(p,{}).state,'none');
assert.equal(core.match(p,{sectors:'ai',stages:'seed',investmentGeographies:'US',check:'750000'}).state,'match');
assert.equal(core.match(p,{stages:'series-a'}).state,'mismatch');
assert.equal(core.match(p,{check:3000001}).state,'mismatch');
assert.equal(core.match(p,{sectors:'food'}).state,'unknown','partial focus must not prove exclusion');
p.publishedCheckRange=null;
assert.equal(core.match(p,{check:1}).state,'unknown','null does not become zero');
p.publishedCheckRange={...source.publishedCheckRange,currency:'EUR'};
