assert.equal(identityMatch(source,{...source,id:'other',slug:'other',officialWebsite:'https://another.example/'}),'review','same name alone is not automatic deduplication');
assert.equal(csv('name,summary\n"A, B","Two\nlines"\n')[0].value.summary,'Two\nlines');
