const store=core.createStore([...many,{...source,id:'hidden',publicationStatus:'hidden'}]);
assert.equal(store.getPublishedInvestorCount(),62);
assert.equal(store.listInvestors({},{}).items.length,25);
assert.equal(store.listInvestors({},{page:3}).items.length,12);
assert.equal(store.listInvestors({query:'not found'}).total,0);
assert.equal(store.listInvestors({criteria:{stages:'series-a'}}).total,0);
assert.equal(store.listInvestors({criteria:{stages:'series-a'},showOutside:true}).total,62);
assert.equal(store.getInvestorBySlug('entity-61').id,'entity-61');
assert.deepEqual(core.restoreShortlist(JSON.stringify({version:1,ids:['deleted',source.id,source.id]}),data),[source.id]);
assert.deepEqual(core.restoreShortlist('broken',data),[]);
assert.equal(core.restoreShortlist(JSON.stringify({version:1,ids:many.map(p=>p.id)}),many).length,20);
assert.equal(identityMatch(source,{...source,id:'other',slug:'other'}),'review');
